#!/usr/bin/env python3
"""Generate src/core/cameras.inc from the Academy's rawtoaces-data (Apache-2.0):
camera spectral sensitivities (380-780 nm, 5 nm) and the 190-patch training reflectances.
Usage: gen_cameras.py <rawtoaces-data checkout> <output .inc>"""
import glob, json, os, sys

src, out = sys.argv[1], sys.argv[2]
cams = []
for f in sorted(glob.glob(os.path.join(src, 'data', 'camera', '*.json'))):
    d = json.load(open(f))
    h, sd = d['header'], d['spectral_data']
    assert h.get('license') == 'Apache-2.0', f
    m = sd['data']['main']
    nms = sorted(m.keys(), key=float)
    assert [float(x) for x in nms] == [380. + 5 * i for i in range(81)], f
    rgb = [[m[n][c] for n in nms] for c in range(3)]
    for c in range(3):
        top = max(rgb[c])
        rgb[c] = [v / top for v in rgb[c]]
    name = '%s %s' % (h['manufacturer'], h['model'])
    ident = os.path.basename(f).replace('_380_780_5.json', '')
    cams.append((ident, name, rgb))
t = json.load(open(os.path.join(src, 'data', 'training', 'training_spectral.json')))['spectral_data']['data']['main']
nms = sorted(t.keys(), key=float)
patches = [[t[n][p] for n in nms] for p in range(len(t[nms[0]]))]

def arr(v):
    return ', '.join('%.6g' % x for x in v)

with open(out, 'w') as o:
    o.write('// Generated by tools/gen_cameras.py from rawtoaces-data (Academy Software Foundation, Apache-2.0,\n')
    o.write('// see third_party/rawtoaces-data/LICENSE). Spectral sensitivities 380-780 nm, 5 nm steps,\n')
    o.write('// each channel normalised to a peak of 1.\n')
    o.write('static const int kCameraCount = %d;\n' % len(cams))
    o.write('static const int kCameraSamples = 81;\n')
    o.write('struct BuiltinCamera { const char* id; const char* name; float s[3][81]; };\n')
    o.write('static const BuiltinCamera kCameras[kCameraCount] = {\n')
    for ident, name, rgb in cams:
        o.write('  { "%s", "%s", {\n' % (ident, name))
        for c in range(3):
            o.write('    { %s },\n' % arr(rgb[c]))
        o.write('  } },\n')
    o.write('};\n')
    o.write('static const int kTrainingCount = %d;\n' % len(patches))
    o.write('static const float kTraining[kTrainingCount][81] = {\n')
    for p in patches:
        o.write('  { %s },\n' % arr(p))
    o.write('};\n')
print(len(cams), 'cameras,', len(patches), 'patches')
