#!/usr/bin/env python3
# ChromaAberrations_OFX - generates src/lens/glasscatalog.inc from the refractiveindex.info
# database (public domain, CC0): https://github.com/polyanskiy/refractiveindex.info-database
#   python3 tools/gen_glass_catalog.py <database>/data-nk/glass > src/lens/glasscatalog.inc
import os, re, sys
import yaml

VENDORS = ["schott", "ohara", "hoya", "cdgm", "hikari", "sumita"]

def main(root):
    out = []
    for v in VENDORS:
        d = os.path.join(root, v)
        if not os.path.isdir(d):
            continue
        for f in sorted(os.listdir(d)):
            if not f.endswith(".yml"):
                continue
            with open(os.path.join(d, f), encoding="utf-8") as fh:
                data = yaml.safe_load(fh)
            for entry in data.get("DATA", []):
                t = str(entry.get("type", "")).strip()
                m = re.match(r"formula (\d+)", t)
                if not m:
                    continue
                kind = int(m.group(1))
                if kind not in (1, 2, 3):
                    continue
                c = [float(x) for x in str(entry["coefficients"]).split()]
                lo, hi = [float(x) for x in str(entry["wavelength_range"]).split()]
                name = f[:-4]
                coefs = ", ".join("%.12g" % x for x in c)
                out.append('{ "%s", "%s", %d, %d, { %s }, %.4g, %.4g },' % (v, name, kind, len(c), coefs, lo, hi))
                break
    print("// Generated by tools/gen_glass_catalog.py from the refractiveindex.info database")
    print("// (public domain, CC0 1.0). Vendor, glass, formula (1 Sellmeier, 2 Sellmeier-2,")
    print("// 3 polynomial), coefficient count, coefficients (wavelength in micrometres), range (um).")
    for l in out:
        print(l)
    sys.stderr.write("%d glasses\n" % len(out))

main(sys.argv[1])
