#!/usr/bin/env python3
# ChromaAberrations_OFX - embeds the .lens files of lenses/ into src/lens/lenses_builtin.inc
#   python3 tools/gen_lenses_builtin.py lenses > src/lens/lenses_builtin.inc
import os, sys
ORDER = ["double_gauss_f2", "wide_angle_100", "telephoto_f56", "cooke_triplet_f5", "petzval_f14"]
d = sys.argv[1]
files = sorted(f[:-5] for f in os.listdir(d) if f.endswith(".lens"))
files = [f for f in ORDER if f in files] + [f for f in files if f not in ORDER]
print("// Generated by tools/gen_lenses_builtin.py from the lenses/ folder")
for f in files:
    text = open(os.path.join(d, f + ".lens"), encoding="utf-8").read()
    # raw string literal, split in chunks (MSVC limits string literals to 16 KB)
    chunks = [text[i:i + 8000] for i in range(0, len(text), 8000)]
    body = " ".join('R"CALENS(%s)CALENS"' % c for c in chunks)
    print('{ "%s", %s },' % (f, body))
